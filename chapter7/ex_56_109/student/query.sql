SELECT 
    B.BOOK_NUM,
    B.BOOK_TITLE,
    A.AU_LNAME,
    A.AU_FNAME,
    C.PAT_ID,
    P.PAT_LNAME,
    P.PAT_TYPE
FROM 
    CHECKOUT C
JOIN BOOK B ON C.BOOK_NUM = B.BOOK_NUM
JOIN WRITES W ON B.BOOK_NUM = W.BOOK_NUM
JOIN AUTHOR A ON W.AU_ID = A.AU_ID
JOIN PATRON P ON C.PAT_ID = P.PAT_ID
WHERE 
    C.CHECK_IN_DATE IS NULL
ORDER BY 
    B.BOOK_TITLE;