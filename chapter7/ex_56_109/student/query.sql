SELECT 
    A.AU_ID,
    A.AU_LNAME,
    B.BOOK_TITLE,
    C.CHECK_OUT_DATE,
    P.PAT_LNAME
FROM 
    AUTHOR A
JOIN WRITES W ON A.AU_ID = W.AU_ID
JOIN BOOK B ON W.BOOK_NUM = B.BOOK_NUM
JOIN CHECKOUT C ON B.BOOK_NUM = C.BOOK_NUM
JOIN PATRON P ON C.PAT_ID = P.PAT_ID
WHERE 
    A.AU_LNAME = 'Bruer'
    AND P.PAT_LNAME = 'Miles'
ORDER BY 
    C.CHECK_OUT_DATE;